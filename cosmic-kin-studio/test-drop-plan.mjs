import assert from 'node:assert/strict';
import {validateDropPlan} from './seadrop-plan.mjs';
const url='https://opensea.io/collection/joshi-astrals';
const plan=validateDropPlan({dropURL:url});
assert.equal(plan.supply,7777);assert.equal(plan.publicSupply+plan.teamSupply,7777);
assert.equal(plan.phases.length,1);assert.equal(plan.phases[0].priceUSDC,'25');assert.equal(plan.perWalletLimit,2);
assert.throws(()=>validateDropPlan({dropURL:'https://opensea.io.evil.test/collection/astrals'}));
assert.throws(()=>validateDropPlan({allowlist:'0x1111111111111111111111111111111111111111'}),/disabled/);
assert.throws(()=>validateDropPlan({dropURL:url,launchStatus:'published'}),/Confirm/);
assert.throws(()=>validateDropPlan({launchStatus:'published',publicationConfirmed:true}),/URL/);
const live=validateDropPlan({dropURL:url,launchStatus:'published',publicationConfirmed:true});
assert.equal(validateDropPlan({dropURL:url},live).launchStatus,'published');
assert.equal(validateDropPlan({launchStatus:'preparation'},live).launchStatus,'preparation');
assert.equal(validateDropPlan({}, {...plan,verification:{arcSeaDropCode:true}}).verification.arcSeaDropCode,true);
console.log('PASS: single public sale, no buyer allowlist, supply totals, official URL, explicit publication confirmation and status preservation.');
